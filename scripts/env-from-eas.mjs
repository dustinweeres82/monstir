#!/usr/bin/env node
/**
 * Generate a local .env from the env block of an eas.json build profile.
 *
 * eas.json is the single source of truth for the app's EXPO_PUBLIC_* config,
 * but its `env` blocks only apply to EAS builds — local `expo start` reads
 * .env instead. Since .env is gitignored, a fresh clone has no local config
 * and the app crashes on startup ("supabaseUrl is required"). This bridges
 * that gap, so setup on any machine is:
 *
 *   git clone … && npm install && npm run env:local
 *
 * Keys already in .env that the profile does not define are preserved, so
 * per-developer values (EXPO_PUBLIC_DEV_EMAIL / EXPO_PUBLIC_DEV_PASSWORD)
 * survive a re-run. Those are deliberately not in eas.json and must never
 * be added to it — every EXPO_PUBLIC_* var is inlined into the shipped
 * bundle, so a dev password there would ship to every user's device.
 *
 * Usage: node scripts/env-from-eas.mjs [profile]     (default: development)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const easPath = resolve(root, 'eas.json');
const envPath = resolve(root, '.env');
const profile = process.argv[2] ?? 'development';

if (!existsSync(easPath)) {
  console.error(`✖ eas.json not found at ${easPath}`);
  process.exit(1);
}

let eas;
try {
  eas = JSON.parse(readFileSync(easPath, 'utf8'));
} catch (err) {
  console.error(`✖ eas.json is not valid JSON: ${err.message}`);
  process.exit(1);
}

const profiles = eas.build ?? {};
const fromEas = profiles[profile]?.env;

if (!fromEas) {
  const available = Object.keys(profiles)
    .filter((p) => profiles[p]?.env)
    .join(', ');
  console.error(
    `✖ Profile "${profile}" has no env block in eas.json.` +
      (available ? ` Profiles with env: ${available}` : '')
  );
  process.exit(1);
}

// Preserve keys the profile doesn't define (per-developer local values).
const preserved = {};
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 1) continue;
    const key = trimmed.slice(0, eq).trim();
    if (!(key in fromEas)) preserved[key] = trimmed.slice(eq + 1);
  }
}

const lines = [
  `# Generated by scripts/env-from-eas.mjs from the "${profile}" profile in eas.json.`,
  `# Do not edit values that come from eas.json — change them there and re-run:`,
  `#   npm run env:local`,
  '',
  ...Object.entries(fromEas).map(([k, v]) => `${k}=${v}`),
];

const preservedKeys = Object.keys(preserved);
if (preservedKeys.length) {
  lines.push('', '# Local-only, not from eas.json (preserved across re-runs).');
  for (const k of preservedKeys) lines.push(`${k}=${preserved[k]}`);
}

writeFileSync(envPath, `${lines.join('\n')}\n`, 'utf8');

// Print names only — never values, so this is safe in CI logs.
console.log(`✔ Wrote .env from eas.json profile "${profile}"`);
console.log(`  from eas.json: ${Object.keys(fromEas).join(', ')}`);
if (preservedKeys.length) console.log(`  preserved local: ${preservedKeys.join(', ')}`);
